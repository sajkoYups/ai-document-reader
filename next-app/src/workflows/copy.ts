export function t(language: OutputLanguage, key: string, vars?: Record<string, string>): string {
  const dict = COPY[language] ?? EN;
  let value = dict[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, v);
    }
  }
  return value;
}
